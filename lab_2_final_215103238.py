# Derive download and upload megabytes in proxy/DLP data where byte columns exist
proxy_name = "ofs_proxy_dlp_logs"
if proxy_name in datasets:
    proxy = datasets[proxy_name]
    download_col = find_column(proxy, ["download_bytes", "bytes_down", "download"])
    upload_col = find_column(proxy, ["upload_bytes", "bytes_up", "upload"])
    if download_col is not None:
        proxy["download_mb"] = proxy[download_col] / (1024 * 1024)
    if upload_col is not None:
        proxy["upload_mb"] = proxy[upload_col] / (1024 * 1024)
    datasets[proxy_name] = proxy

# Derive new geography and new device indicators from VPN logs
vpn_name = "ofs_vpn_authentication_logs"
if vpn_name in datasets:
    vpn = datasets[vpn_name].copy()
    user_col = find_column(vpn, ["user", "username", "account"])
    geo_col = find_column(vpn, ["country", "geo", "location"])
    device_col = find_column(vpn, ["device", "host", "hostname"])
    if user_col is not None and geo_col is not None:
        vpn["is_new_geography"] = vpn.groupby(user_col)[geo_col].transform(lambda x: ~x.duplicated())
    if user_col is not None and device_col is not None:
        vpn["is_new_device"] = vpn.groupby(user_col)[device_col].transform(lambda x: ~x.duplicated())
    datasets[vpn_name] = vpn

# Add resource sensitivity to file-access logs by matching policy/resource labels
file_access_name = "ofs_file_access_logs"
policy_name = "ofs_access_policy_matrix"
directory_name = "ofs_employee_directory"

if file_access_name in datasets:
    file_access = datasets[file_access_name].copy()
    resource_col = find_column(file_access, ["resource", "file", "path"])

    # Rule-based sensitivity fallback if no direct policy join is possible
    def classify_sensitivity(value):
        value = str(value).lower()
        if any(term in value for term in ["confidential", "restricted", "payroll", "hr", "finance", "audit"]):
            return "High"
        if any(term in value for term in ["internal", "operations", "customer"]):
            return "Medium"
        return "Low"

    if resource_col is not None:
        file_access["resource_sensitivity"] = file_access[resource_col].apply(classify_sensitivity)

    # Role mismatch detection using employee role and expected access policy, where matching fields exist
    if policy_name in datasets and directory_name in datasets:
        policy = datasets[policy_name].copy()
        directory = datasets[directory_name].copy()
        fa_user_col = find_column(file_access, ["user", "username", "account"])
        dir_user_col = find_column(directory, ["user", "username", "account", "employee"])
        role_col = find_column(directory, ["role", "job", "department"])
        policy_role_col = find_column(policy, ["role", "job", "department"])
        policy_resource_col = find_column(policy, ["resource", "file", "path"])
        if all(col is not None for col in [fa_user_col, dir_user_col, role_col, policy_role_col, policy_resource_col, resource_col]):
            file_access = file_access.merge(directory[[dir_user_col, role_col]], left_on=fa_user_col, right_on=dir_user_col, how="left")
            allowed = policy[[policy_role_col, policy_resource_col]].drop_duplicates()
            file_access = file_access.merge(allowed, left_on=[role_col, resource_col], right_on=[policy_role_col, policy_resource_col], how="left", indicator=True)
            file_access["role_mismatch"] = file_access["_merge"].eq("left_only")
            file_access = file_access.drop(columns=["_merge"])
    datasets[file_access_name] = file_access

