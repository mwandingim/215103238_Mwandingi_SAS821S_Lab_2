# Load the supplied training dataset
training_file = "ofs_access_session_training.csv"
df = pd.read_csv(training_file)

# Display basic structure for reproducibility
print("Dataset shape:", df.shape)
print("\nColumns:")
print(df.columns.tolist())

print("\nData types:")
print(df.dtypes)

print("\nMissing values:")
print(df.isna().sum())

# ------------------------------------------------------------
# Identify the target label
# ------------------------------------------------------------
# Adjust this if the supplied data dictionary uses a different label name.
possible_targets = [
    "label",
    "risk_label",
    "is_malicious",
    "is_suspicious",
    "incident_label",
    "class"
]

target_col = None
for col in possible_targets:
    if col in df.columns:
        target_col = col
        break

if target_col is None:
    raise ValueError(
        "No target label column found. Check the data dictionary "
        "and update target_col manually."
    )

print("\nTarget column:", target_col)
print(df[target_col].value_counts())

# ------------------------------------------------------------
# Select behavioural access-risk features
# ------------------------------------------------------------
# Remove obvious identifiers and the target label from model features.
identifier_cols = [
    "session_id",
    "event_id",
    "user",
    "username",
    "user_id",
    "account",
    "timestamp",
    "date",
    "time"
]

drop_cols = [col for col in identifier_cols if col in df.columns]
drop_cols.append(target_col)

X = df.drop(columns=drop_cols)
y = df[target_col]

# Separate numeric and categorical features
numeric_features = X.select_dtypes(include=["int64", "float64", "int32", "float32"]).columns.tolist()
categorical_features = X.select_dtypes(include=["object", "bool", "category"]).columns.tolist()

print("\nNumeric features:", numeric_features)
print("Categorical features:", categorical_features)

# ------------------------------------------------------------
# Create stratified 70/30 training-test split
# ------------------------------------------------------------
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.30,
    random_state=42,
    stratify=y
)

print("\nTraining set size:", X_train.shape)
print("Test set size:", X_test.shape)

print("\nTraining label distribution:")
print(y_train.value_counts(normalize=True))

print("\nTest label distribution:")
print(y_test.value_counts(normalize=True))

# ------------------------------------------------------------
# Build preprocessing and classifier pipeline
# ------------------------------------------------------------
preprocessor = ColumnTransformer(
    transformers=[
        ("num", StandardScaler(), numeric_features),
        ("cat", OneHotEncoder(handle_unknown="ignore"), categorical_features)
    ]
)

model = RandomForestClassifier(
    n_estimators=200,
    random_state=42,
    class_weight="balanced"
)

clf = Pipeline(
    steps=[
        ("preprocessor", preprocessor),
        ("model", model)
    ]
)

# ------------------------------------------------------------
# Train the supervised classifier
# ------------------------------------------------------------
clf.fit(X_train, y_train)

# ------------------------------------------------------------
# Evaluate the model
# ------------------------------------------------------------
y_pred = clf.predict(X_test)

print("\nAccuracy:", accuracy_score(y_test, y_pred))

print("\nConfusion matrix:")
print(confusion_matrix(y_test, y_pred))

print("\nClassification report:")
print(classification_report(y_test, y_pred))

