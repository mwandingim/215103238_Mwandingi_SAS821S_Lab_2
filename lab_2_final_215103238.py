# Helper function to find columns by likely keywords
def find_column(df, keywords):
    for col in df.columns:
        if any(keyword in col.lower() for keyword in keywords):
            return col
    return None

# Add time-based fields to every dataset with a timestamp column
for name, df in datasets.items():
    timestamp_col = find_column(df, ["timestamp", "time", "date"])
    if timestamp_col is not None:
        df["event_hour"] = df[timestamp_col].dt.hour
        df["event_day_of_week"] = df[timestamp_col].dt.day_name()
        df["is_weekend"] = df[timestamp_col].dt.dayofweek.isin([5, 6])
        df["is_off_hours"] = ~df["event_hour"].between(8, 17)
